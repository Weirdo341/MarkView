const { contextBridge, ipcRenderer, webUtils } = require('electron');
const path = require('path');
const { pathToFileURL } = require('url');

const LISTEN_CHANNELS = new Set([
  'file:opened',
  'file:changed',
  'theme:set',
  'zoom:changed',
  'pandoc:export',
  'menu:integration-settings',
  'menu:history',
  'menu:find',
  'menu:toggle-sidebar',
  'pdf:prepare',
  'image:prepare',
  'font:set',
  'menu:save',
  'menu:undo',
  'menu:redo',
  'wide:set',
  'focus:set',
  'typewriter:set',
  'menu:toggle-edit',
  'menu:insert',
  'menu:typography',
  'menu:check-update',
  'menu:copy-md',
  'menu:copy-html',
  'html:prepare',
  'html:prepare-bare',
  'spellcheck:set',
  'language:set',
  'direction:set',
  'customCss:set',
  'customCss:reload',
  'find:result',
  'recent:cleared',
]);

contextBridge.exposeInMainWorld('api', {
  openDialog: () => ipcRenderer.invoke('dialog:open'),
  openPath: (p) => ipcRenderer.invoke('file:open', p),
  getConfig: () => ipcRenderer.invoke('config:get'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  readDir: (p) => ipcRenderer.invoke('fs:tree', p),
  articles: (p) => ipcRenderer.invoke('fs:articles', p),
  searchFiles: (dir, q) => ipcRenderer.invoke('fs:search', dir, q),
  imageData: (p) => ipcRenderer.invoke('html:imageData', p),
  setConfig: (patch) => ipcRenderer.invoke('config:set', patch),
  customCss: () => ipcRenderer.invoke('customCss:get'),
  reloadCustomCss: () => ipcRenderer.invoke('customCss:reload'),
  samplePath: () => ipcRenderer.invoke('app:samplePath'),
  version: () => ipcRenderer.invoke('app:version'),
  locale: () => ipcRenderer.invoke('app:locale'),
  saveFile: (content) => ipcRenderer.invoke('file:save', content),
  historyList: (file) => ipcRenderer.invoke('history:list', file),
  historyRestore: (file, id) => ipcRenderer.invoke('history:restore', file, id),
  pandocStatus: () => ipcRenderer.invoke('pandoc:status'),
  exportPandoc: (format) => ipcRenderer.invoke('pandoc:export', format),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  pickImage: () => ipcRenderer.invoke('dialog:image'),
  savePaste: (payload) => ipcRenderer.invoke('image:savePaste', payload),
  uploadImage: (file) => ipcRenderer.invoke('image:upload', file),
  relPath: (from, to) => path.relative(from, to),
  editChanged: (on) => ipcRenderer.send('edit:changed', on),
  exportPdf: () => ipcRenderer.invoke('pdf:export'),
  exportImage: (dims) => ipcRenderer.invoke('image:export', dims),
  exportHtml: (html) => ipcRenderer.invoke('html:export', html),
  htmlAssets: () => ipcRenderer.invoke('html:assets'),
  openExternal: (url) => ipcRenderer.invoke('shell:openExternal', url),
  openLocal: (p) => ipcRenderer.invoke('shell:openPath', p),
  setZoom: (level) => ipcRenderer.invoke('zoom:set', level),
  find: (text, opts) => ipcRenderer.send('find:start', text, opts),
  stopFind: () => ipcRenderer.send('find:stop'),
  renderDone: (info) => ipcRenderer.send('render:done', info),
  getPathForFile: (file) => webUtils.getPathForFile(file),
  resolvePath: (dir, rel) => path.resolve(dir, rel),
  toFileURL: (p) => pathToFileURL(p).href,
  basename: (p) => path.basename(p),
  dirname: (p) => path.dirname(p),
  extname: (p) => path.extname(p),
  on: (channel, listener) => {
    if (!LISTEN_CHANNELS.has(channel)) return () => {};
    const wrapped = (event, ...args) => listener(...args);
    ipcRenderer.on(channel, wrapped);
    return () => ipcRenderer.removeListener(channel, wrapped);
  },
});